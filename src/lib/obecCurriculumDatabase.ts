/**
 * Intelligent matcher to find OBEC standard indicators from curriculum database
 * based on subject, grade level, and unit text keywords.
 */
export function findStandardIndicatorsForUnit(params: {
  subject: string;
  gradeLevel: string;
  unitName: string;
}): StandardIndicator[] {
  const { subject, gradeLevel, unitName } = params;
  if (!unitName) return [];

  const cleanSubject = subject.toLowerCase().trim();
  const cleanGrade = gradeLevel.replace(/\s+/g, '').trim();
  const cleanUnit = unitName.toLowerCase();

  // Find subject category
  let matchedCategory: SubjectCurriculum | undefined;
  if (cleanSubject.includes('คณิต') || cleanSubject.includes('math')) {
    matchedCategory = OBEC_CURRICULUM_DATABASE.math;
  } else if (cleanSubject.includes('วิทย์') || cleanSubject.includes('sci')) {
    matchedCategory = OBEC_CURRICULUM_DATABASE.science;
  } else if (cleanSubject.includes('ไทย') || cleanSubject.includes('thai')) {
    matchedCategory = OBEC_CURRICULUM_DATABASE.thai;
  }

  if (!matchedCategory) return [];

  // Match grade level (e.g. "ป.5" from "ป.5/1" or "ชั้นประถมศึกษาปีที่ 5")
  let gradeKey = Object.keys(matchedCategory.gradeLevels).find(
    (g) => cleanGrade.includes(g) || g.includes(cleanGrade)
  );
  if (!gradeKey) {
    if (cleanGrade.includes('5') || cleanGrade.includes('ประถม 5')) gradeKey = 'ป.5';
    else if (cleanGrade.includes('4') || cleanGrade.includes('ประถม 4')) gradeKey = 'ป.4';
    else if (cleanGrade.includes('6') || cleanGrade.includes('ประถม 6')) gradeKey = 'ป.6';
    else if (cleanGrade.includes('1') || cleanGrade.includes('มัธยม 1')) gradeKey = 'ม.1';
    else if (cleanGrade.includes('2') || cleanGrade.includes('มัธยม 2')) gradeKey = 'ม.2';
    else if (cleanGrade.includes('3') || cleanGrade.includes('มัธยม 3')) gradeKey = 'ม.3';
  }

  const indicatorsForGrade = gradeKey ? matchedCategory.gradeLevels[gradeKey] : undefined;
  if (!indicatorsForGrade || indicatorsForGrade.length === 0) return [];

  // Score indicators by keyword match with unitName
  const scored = indicatorsForGrade
    .map((ind) => {
      let score = 0;
      for (const kw of ind.keywords) {
        if (cleanUnit.includes(kw.toLowerCase())) {
          score += 10;
        }
      }
      if (cleanUnit.includes(ind.name.slice(0, 10).toLowerCase())) {
        score += 5;
      }
      return { ind, score };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);

  if (scored.length > 0) {
    // Return top 1-3 matching indicators
    return scored.slice(0, 3).map((s) => s.ind);
  }

  // Fallback: If no keyword matched, provide the first 2-3 standard indicators of that grade
  if (indicatorsForGrade && indicatorsForGrade.length > 0) {
    return indicatorsForGrade.slice(0, 2);
  }

  return [];
}
